#!/usr/bin/env node
'use strict';
// Builds the claude.ai Chrome extension into extension/dist/ (load it with "Load unpacked").
//
// The engine is NOT copied: this script bundles scripts/lib/* straight from the repo into one
// classic script (an IIFE) that content scripts can load. Node built-ins used by the loaders
// (fs, path, os) are swapped for the small shims in src/shims/. No dependencies.
const fs = require('fs');
const path = require('path');

const EXT = __dirname;
const ROOT = path.resolve(EXT, '..');
const SRC = path.join(EXT, 'src');
const OUT = path.join(EXT, 'dist');
const ENTRY = path.join(SRC, 'core.js');
const SHIMS = new Set(['fs', 'path', 'os']);
const COPY = ['manifest.json', 'content.js', 'popup.html', 'popup.js'];

function resolveRequire(fromDir, req) {
  if (SHIMS.has(req)) return 'shim:' + req;
  if (req.startsWith('@packs/')) return path.join(ROOT, 'packs', req.slice('@packs/'.length));
  if (req.startsWith('.')) {
    let f = path.resolve(fromDir, req);
    if (!fs.existsSync(f) && fs.existsSync(f + '.js')) f += '.js';
    return f;
  }
  throw new Error(`browser bundle cannot require "${req}" (from ${fromDir})`);
}

function collect(entry) {
  const graph = new Map();
  const visit = (key) => {
    if (graph.has(key)) return;
    if (key.startsWith('shim:')) {
      const code = fs.readFileSync(path.join(SRC, 'shims', key.slice(5) + '.js'), 'utf8');
      graph.set(key, { code, deps: {} });
      return;
    }
    const raw = fs.readFileSync(key, 'utf8');
    const code = key.endsWith('.json') ? 'module.exports = ' + raw.trim() + ';' : raw;
    const deps = {};
    for (const m of code.matchAll(/require\((['"])([^'"]+)\1\)/g)) {
      if (!(m[2] in deps)) deps[m[2]] = resolveRequire(path.dirname(key), m[2]);
    }
    graph.set(key, { code, deps });
    for (const k of Object.values(deps)) visit(k);
  };
  visit(entry);
  return graph;
}

function bundle() {
  const graph = collect(ENTRY);
  const keys = [...graph.keys()];
  const index = new Map(keys.map((k, i) => [k, i]));
  const defs = keys.map((k) => {
    const { code, deps } = graph.get(k);
    const depMap = Object.fromEntries(Object.entries(deps).map(([req, target]) => [req, index.get(target)]));
    return `  ${index.get(k)}: [function (module, exports, require, __dirname, process) {\n${code}\n}, ${JSON.stringify(depMap)}]`;
  });
  return [
    '/* PromptGate engine bundle. Generated by extension/build.js from scripts/lib/. Do not edit. */',
    '(function () {',
    '  "use strict";',
    '  var defs = {',
    defs.join(',\n'),
    '  };',
    '  var cache = {};',
    '  function load(id) {',
    '    if (cache[id]) return cache[id].exports;',
    '    var def = defs[id];',
    '    var mod = { exports: {} };',
    '    cache[id] = mod;',
    '    var local = function (req) { return load(def[1][req]); };',
    '    def[0].call(mod.exports, mod, mod.exports, local, "", { env: {}, platform: "browser" });',
    '    return mod.exports;',
    '  }',
    `  globalThis.PromptGateCore = load(${index.get(ENTRY)});`,
    '})();',
    '',
  ].join('\n');
}

function build(opts) {
  opts = opts || {};
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const code = bundle();
  fs.writeFileSync(path.join(OUT, 'engine.js'), code);
  for (const f of COPY) fs.copyFileSync(path.join(SRC, f), path.join(OUT, f));
  const icons = require('./src/icons');
  fs.mkdirSync(path.join(OUT, 'icons'), { recursive: true });
  for (const s of icons.SIZES) fs.writeFileSync(path.join(OUT, 'icons', `${s}.png`), icons.png(s));
  if (!opts.quiet) console.log(`built ${path.relative(ROOT, OUT)}/ (engine.js ${Buffer.byteLength(code)} bytes, ${icons.SIZES.length} icons)`);
  if (opts.zip) {
    // Chrome Web Store upload: a zip whose root holds manifest.json. Written to <repo>/dist/.
    const { execSync } = require('child_process');
    const manifest = JSON.parse(fs.readFileSync(path.join(OUT, 'manifest.json'), 'utf8'));
    const zipDir = path.join(ROOT, 'dist');
    fs.mkdirSync(zipDir, { recursive: true });
    const zip = path.join(zipDir, `promptgate-extension-${manifest.version}.zip`);
    fs.rmSync(zip, { force: true });
    if (process.platform === 'win32') execSync(`powershell -NoProfile -Command "Compress-Archive -Path '${OUT}\\*' -DestinationPath '${zip}' -Force"`);
    else execSync(`cd "${OUT}" && zip -qr "${zip}" .`);
    if (!opts.quiet) console.log(`zip ${path.relative(ROOT, zip)} (${fs.statSync(zip).size} bytes)`);
  }
  return OUT;
}

module.exports = { build, bundle };

if (require.main === module) build({ zip: process.argv.includes('--zip') });
